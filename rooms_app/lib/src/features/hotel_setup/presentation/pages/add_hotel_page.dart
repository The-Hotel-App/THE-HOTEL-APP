import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:go_router/go_router.dart';
import 'package:rooms/src/core/constants/app_colors.dart';
import 'package:rooms/src/core/services/supabase_service.dart';
import 'package:rooms/src/features/auth/presentation/providers/auth_providers_new.dart';
import 'package:rooms/src/features/hotel_setup/domain/entities/hotel_new.dart';
import 'package:rooms/src/features/hotel_setup/data/repositories/supabase_hotel_setup_repository.dart';

/// Local room type for setup (before hotel is created)
class LocalRoomType {
  final String name;
  final double basePrice;
  final int maxOccupancy;
  final String? description;

  LocalRoomType({
    required this.name,
    required this.basePrice,
    required this.maxOccupancy,
    this.description,
  });
}

/// Simple Add Hotel Page - Minimal form to create a new hotel
class AddHotelPage extends ConsumerStatefulWidget {
  const AddHotelPage({super.key});

  @override
  ConsumerState<AddHotelPage> createState() => _AddHotelPageState();
}

class _AddHotelPageState extends ConsumerState<AddHotelPage> {
  final _formKey = GlobalKey<FormState>();
  final _nameController = TextEditingController();
  final _addressController = TextEditingController();
  
  int _totalFloors = 1;
  final Map<int, int> _roomsPerFloor = {1: 10};
  final List<LocalRoomType> _roomTypes = [];
  
  bool _isLoading = false;
  String? _error;

  @override
  void dispose() {
    _nameController.dispose();
    _addressController.dispose();
    super.dispose();
  }

  void _updateFloors(int newValue) {
    setState(() {
      _totalFloors = newValue;
      for (int i = 1; i <= newValue; i++) {
        _roomsPerFloor.putIfAbsent(i, () => 10);
      }
      _roomsPerFloor.removeWhere((floor, _) => floor > newValue);
    });
  }

  Future<void> _createHotel() async {
    if (!_formKey.currentState!.validate()) return;

    setState(() {
      _isLoading = true;
      _error = null;
    });

    try {
      final user = SupabaseService.instance.client.auth.currentUser;
      if (user == null) {
        throw Exception('Not authenticated');
      }

      // Get owner's email and phone from user metadata
      final userEmail = user.email;
      final userPhone = user.phone ?? user.userMetadata?['phone'] as String?;

      // Build floor configs
      final floorConfigs = <FloorConfig>[];
      int currentRoomStart = 1;
      
      for (int floor = 1; floor <= _totalFloors; floor++) {
        final roomCount = _roomsPerFloor[floor] ?? 10;
        floorConfigs.add(FloorConfig(
          floor: floor,
          startRoom: currentRoomStart,
          endRoom: currentRoomStart + roomCount - 1,
        ));
        currentRoomStart += roomCount;
      }

      final repository = SupabaseHotelSetupRepository();
      
      // Create the hotel
      final hotel = await repository.createHotel(
        name: _nameController.text.trim(),
        address: _addressController.text.trim(),
        phone: userPhone,
        email: userEmail,
        totalFloors: _totalFloors,
        floorConfigs: floorConfigs,
        ownerId: user.id,
        hotelCode: null,
      );

      // Create room types if any
      if (_roomTypes.isNotEmpty) {
        await repository.createRoomTypes(
          hotelId: hotel.id,
          roomTypes: _roomTypes.map((rt) => RoomType(
            id: '', // Will be generated by database
            hotelId: hotel.id,
            name: rt.name,
            basePrice: rt.basePrice,
            maxOccupancy: rt.maxOccupancy,
            description: rt.description,
          )).toList(),
        );
      }

      // Create rooms
      await repository.createRooms(
        hotelId: hotel.id,
        floorConfigs: floorConfigs,
        roomTypeAssignments: {},
      );

      // Mark setup as completed
      await repository.completeSetup(hotel.id);

      // Refresh hotels list and select the new hotel
      ref.invalidate(userHotelsProvider);
      ref.read(selectedHotelIdProvider.notifier).state = hotel.id;

      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text('Hotel "${hotel.name}" created successfully!'),
            backgroundColor: AppColors.success,
          ),
        );
        context.go('/main');
      }
    } catch (e) {
      setState(() {
        _error = e.toString();
        _isLoading = false;
      });
    }
  }

  void _showAddEditRoomTypeDialog([LocalRoomType? roomType, int? index]) {
    final isEditing = roomType != null;
    final nameController = TextEditingController(text: roomType?.name ?? '');
    final priceController = TextEditingController(
      text: roomType?.basePrice.toStringAsFixed(0) ?? '',
    );
    final occupancyController = TextEditingController(
      text: roomType?.maxOccupancy.toString() ?? '2',
    );
    final descriptionController = TextEditingController(
      text: roomType?.description ?? '',
    );
    final formKey = GlobalKey<FormState>();

    showDialog(
      context: context,
      builder: (context) => AlertDialog(
        title: Text(isEditing ? 'Edit Room Type' : 'Add Room Type'),
        content: Form(
          key: formKey,
          child: SingleChildScrollView(
            child: Column(
              mainAxisSize: MainAxisSize.min,
              children: [
                TextFormField(
                  controller: nameController,
                  decoration: const InputDecoration(
                    labelText: 'Name *',
                    hintText: 'Deluxe, Suite, Standard...',
                  ),
                  validator: (v) => v?.isEmpty ?? true ? 'Required' : null,
                ),
                const SizedBox(height: 12),
                TextFormField(
                  controller: priceController,
                  decoration: const InputDecoration(
                    labelText: 'Price/Night (₹) *',
                    hintText: '1500',
                  ),
                  keyboardType: TextInputType.number,
                  validator: (v) => v?.isEmpty ?? true ? 'Required' : null,
                ),
                const SizedBox(height: 12),
                TextFormField(
                  controller: occupancyController,
                  decoration: const InputDecoration(
                    labelText: 'Max Guests *',
                    hintText: '2',
                  ),
                  keyboardType: TextInputType.number,
                  validator: (v) => v?.isEmpty ?? true ? 'Required' : null,
                ),
                const SizedBox(height: 12),
                TextFormField(
                  controller: descriptionController,
                  decoration: const InputDecoration(
                    labelText: 'Description',
                    hintText: 'Optional',
                  ),
                  maxLines: 2,
                ),
              ],
            ),
          ),
        ),
        actions: [
          TextButton(
            onPressed: () => Navigator.pop(context),
            child: const Text('Cancel'),
          ),
          ElevatedButton(
            onPressed: () {
              if (!formKey.currentState!.validate()) return;

              final newRoomType = LocalRoomType(
                name: nameController.text.trim(),
                basePrice: double.tryParse(priceController.text) ?? 0,
                maxOccupancy: int.tryParse(occupancyController.text) ?? 2,
                description: descriptionController.text.trim().isEmpty
                    ? null
                    : descriptionController.text.trim(),
              );

              setState(() {
                if (isEditing && index != null) {
                  _roomTypes[index] = newRoomType;
                } else {
                  _roomTypes.add(newRoomType);
                }
              });

              Navigator.pop(context);
            },
            style: ElevatedButton.styleFrom(backgroundColor: AppColors.black),
            child: Text(isEditing ? 'Update' : 'Add'),
          ),
        ],
      ),
    );
  }

  void _deleteRoomType(int index) {
    showDialog(
      context: context,
      builder: (context) => AlertDialog(
        title: const Text('Delete Room Type?'),
        content: Text('Delete "${_roomTypes[index].name}"?'),
        actions: [
          TextButton(
            onPressed: () => Navigator.pop(context),
            child: const Text('Cancel'),
          ),
          ElevatedButton(
            onPressed: () {
              setState(() => _roomTypes.removeAt(index));
              Navigator.pop(context);
            },
            style: ElevatedButton.styleFrom(backgroundColor: AppColors.error),
            child: const Text('Delete'),
          ),
        ],
      ),
    );
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      backgroundColor: AppColors.grey100,
      appBar: AppBar(
        backgroundColor: AppColors.black,
        foregroundColor: AppColors.white,
        leading: IconButton(
          icon: const Icon(Icons.close),
          onPressed: () => context.pop(),
        ),
        title: const Text('Add New Hotel'),
      ),
      body: SingleChildScrollView(
        padding: const EdgeInsets.all(20),
        child: Form(
          key: _formKey,
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              // Header
              const Text(
                'Hotel Details',
                style: TextStyle(fontSize: 24, fontWeight: FontWeight.bold),
              ),
              const SizedBox(height: 8),
              Text(
                'Enter basic information about your hotel property.',
                style: TextStyle(color: AppColors.grey600),
              ),
              const SizedBox(height: 24),

              // Hotel Name
              _buildInputCard(
                child: TextFormField(
                  controller: _nameController,
                  decoration: const InputDecoration(
                    labelText: 'Hotel Name *',
                    hintText: 'e.g., Grand Palace Hotel',
                    prefixIcon: Icon(Icons.hotel),
                    border: OutlineInputBorder(),
                  ),
                  validator: (value) {
                    if (value == null || value.trim().isEmpty) {
                      return 'Hotel name is required';
                    }
                    return null;
                  },
                ),
              ),
              const SizedBox(height: 16),

              // Address
              _buildInputCard(
                child: TextFormField(
                  controller: _addressController,
                  decoration: const InputDecoration(
                    labelText: 'Address *',
                    hintText: 'Full hotel address',
                    prefixIcon: Icon(Icons.location_on),
                    border: OutlineInputBorder(),
                  ),
                  maxLines: 2,
                  validator: (value) {
                    if (value == null || value.trim().isEmpty) {
                      return 'Address is required';
                    }
                    return null;
                  },
                ),
              ),
              const SizedBox(height: 24),

              // Room Configuration Section
              const Text(
                'Room Configuration',
                style: TextStyle(fontSize: 20, fontWeight: FontWeight.bold),
              ),
              const SizedBox(height: 16),

              // Total Floors
              _buildInputCard(
                child: Row(
                  children: [
                    const Icon(Icons.layers, color: AppColors.grey600),
                    const SizedBox(width: 12),
                    const Expanded(
                      child: Text('Number of Floors', style: TextStyle(fontSize: 16)),
                    ),
                    IconButton(
                      onPressed: _totalFloors > 1
                          ? () => _updateFloors(_totalFloors - 1)
                          : null,
                      icon: const Icon(Icons.remove_circle_outline),
                      color: AppColors.warning,
                    ),
                    Container(
                      padding: const EdgeInsets.symmetric(horizontal: 16, vertical: 8),
                      decoration: BoxDecoration(
                        color: AppColors.grey100,
                        borderRadius: BorderRadius.circular(8),
                      ),
                      child: Text(
                        '$_totalFloors',
                        style: const TextStyle(fontSize: 18, fontWeight: FontWeight.bold),
                      ),
                    ),
                    IconButton(
                      onPressed: _totalFloors < 20
                          ? () => _updateFloors(_totalFloors + 1)
                          : null,
                      icon: const Icon(Icons.add_circle_outline),
                      color: AppColors.warning,
                    ),
                  ],
                ),
              ),
              const SizedBox(height: 16),

              // Rooms per floor
              _buildInputCard(
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    const Row(
                      children: [
                        Icon(Icons.bed, color: AppColors.grey600),
                        SizedBox(width: 12),
                        Text('Rooms per Floor', style: TextStyle(fontSize: 16)),
                      ],
                    ),
                    const SizedBox(height: 12),
                    ...List.generate(_totalFloors, (index) {
                      final floor = index + 1;
                      return Padding(
                        padding: const EdgeInsets.only(bottom: 8),
                        child: Row(
                          children: [
                            Container(
                              width: 32,
                              height: 32,
                              decoration: BoxDecoration(
                                color: AppColors.black,
                                borderRadius: BorderRadius.circular(6),
                              ),
                              child: Center(
                                child: Text(
                                  '$floor',
                                  style: const TextStyle(color: AppColors.white, fontWeight: FontWeight.bold, fontSize: 14),
                                ),
                              ),
                            ),
                            const SizedBox(width: 8),
                            Expanded(child: Text('Floor $floor')),
                            SizedBox(
                              width: 70,
                              child: TextFormField(
                                initialValue: '${_roomsPerFloor[floor] ?? 10}',
                                decoration: const InputDecoration(
                                  border: OutlineInputBorder(),
                                  contentPadding: EdgeInsets.symmetric(horizontal: 8, vertical: 8),
                                ),
                                keyboardType: TextInputType.number,
                                textAlign: TextAlign.center,
                                onChanged: (value) {
                                  final rooms = int.tryParse(value) ?? 10;
                                  setState(() => _roomsPerFloor[floor] = rooms.clamp(1, 100));
                                },
                              ),
                            ),
                          ],
                        ),
                      );
                    }),
                  ],
                ),
              ),
              const SizedBox(height: 24),

              // Room Types Section
              Row(
                mainAxisAlignment: MainAxisAlignment.spaceBetween,
                children: [
                  const Text(
                    'Room Types',
                    style: TextStyle(fontSize: 20, fontWeight: FontWeight.bold),
                  ),
                  TextButton.icon(
                    onPressed: () => _showAddEditRoomTypeDialog(),
                    icon: const Icon(Icons.add, size: 18),
                    label: const Text('Add'),
                    style: TextButton.styleFrom(foregroundColor: AppColors.warning),
                  ),
                ],
              ),
              const SizedBox(height: 8),
              Text(
                'Optional: Define room types now or add them later.',
                style: TextStyle(color: AppColors.grey600, fontSize: 13),
              ),
              const SizedBox(height: 12),

              if (_roomTypes.isEmpty)
                _buildInputCard(
                  color: AppColors.grey100,
                  child: const Center(
                    child: Padding(
                      padding: EdgeInsets.all(16),
                      child: Text(
                        'No room types added yet',
                        style: TextStyle(color: AppColors.grey500),
                      ),
                    ),
                  ),
                )
              else
                ...List.generate(_roomTypes.length, (index) {
                  final rt = _roomTypes[index];
                  return Container(
                    margin: const EdgeInsets.only(bottom: 8),
                    decoration: BoxDecoration(
                      color: AppColors.white,
                      borderRadius: BorderRadius.circular(12),
                      boxShadow: [
                        BoxShadow(
                          color: Colors.black.withValues(alpha: 0.05),
                          blurRadius: 8,
                          offset: const Offset(0, 2),
                        ),
                      ],
                    ),
                    child: ListTile(
                      leading: Container(
                        width: 40,
                        height: 40,
                        decoration: BoxDecoration(
                          color: AppColors.warning.withValues(alpha: 0.1),
                          borderRadius: BorderRadius.circular(8),
                        ),
                        child: const Icon(Icons.bedroom_parent, color: AppColors.warning, size: 20),
                      ),
                      title: Text(rt.name, style: const TextStyle(fontWeight: FontWeight.w600)),
                      subtitle: Text('₹${rt.basePrice.toStringAsFixed(0)}/night • Max ${rt.maxOccupancy} guests'),
                      trailing: Row(
                        mainAxisSize: MainAxisSize.min,
                        children: [
                          IconButton(
                            icon: const Icon(Icons.edit, size: 18),
                            onPressed: () => _showAddEditRoomTypeDialog(rt, index),
                          ),
                          IconButton(
                            icon: const Icon(Icons.delete, size: 18, color: AppColors.error),
                            onPressed: () => _deleteRoomType(index),
                          ),
                        ],
                      ),
                    ),
                  );
                }),
              const SizedBox(height: 16),

              // Summary
              _buildInputCard(
                color: AppColors.success.withValues(alpha: 0.1),
                child: Row(
                  children: [
                    const Icon(Icons.summarize, color: AppColors.success),
                    const SizedBox(width: 12),
                    Column(
                      crossAxisAlignment: CrossAxisAlignment.start,
                      children: [
                        const Text('Total Rooms', style: TextStyle(color: AppColors.grey600)),
                        Text(
                          '${_roomsPerFloor.values.fold(0, (a, b) => a + b)}',
                          style: const TextStyle(fontSize: 24, fontWeight: FontWeight.bold, color: AppColors.success),
                        ),
                      ],
                    ),
                    const Spacer(),
                    Column(
                      crossAxisAlignment: CrossAxisAlignment.start,
                      children: [
                        const Text('Room Types', style: TextStyle(color: AppColors.grey600)),
                        Text(
                          '${_roomTypes.length}',
                          style: const TextStyle(fontSize: 24, fontWeight: FontWeight.bold, color: AppColors.success),
                        ),
                      ],
                    ),
                  ],
                ),
              ),

              // Error message
              if (_error != null) ...[
                const SizedBox(height: 16),
                Container(
                  padding: const EdgeInsets.all(12),
                  decoration: BoxDecoration(
                    color: AppColors.error.withValues(alpha: 0.1),
                    borderRadius: BorderRadius.circular(8),
                    border: Border.all(color: AppColors.error.withValues(alpha: 0.3)),
                  ),
                  child: Row(
                    children: [
                      const Icon(Icons.error, color: AppColors.error),
                      const SizedBox(width: 12),
                      Expanded(child: Text(_error!, style: const TextStyle(color: AppColors.error))),
                    ],
                  ),
                ),
              ],

              const SizedBox(height: 32),

              // Create Button
              SizedBox(
                width: double.infinity,
                height: 56,
                child: ElevatedButton(
                  onPressed: _isLoading ? null : _createHotel,
                  style: ElevatedButton.styleFrom(
                    backgroundColor: AppColors.warning,
                    foregroundColor: AppColors.black,
                    shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(12)),
                  ),
                  child: _isLoading
                      ? const SizedBox(
                          width: 24,
                          height: 24,
                          child: CircularProgressIndicator(strokeWidth: 2, color: AppColors.black),
                        )
                      : const Text('Create Hotel', style: TextStyle(fontSize: 18, fontWeight: FontWeight.bold)),
                ),
              ),
              const SizedBox(height: 24),
            ],
          ),
        ),
      ),
    );
  }

  Widget _buildInputCard({required Widget child, Color? color}) {
    return Container(
      padding: const EdgeInsets.all(16),
      decoration: BoxDecoration(
        color: color ?? AppColors.white,
        borderRadius: BorderRadius.circular(12),
        boxShadow: [
          BoxShadow(
            color: Colors.black.withValues(alpha: 0.05),
            blurRadius: 10,
            offset: const Offset(0, 4),
          ),
        ],
      ),
      child: child,
    );
  }
}
